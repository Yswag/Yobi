export type Provider = "yt" | "bili"

export type YoutubeStreamPreference = "auto" | "hls" | "sabr"

export interface UnifiedVideoItem {
  id: string // e.g. "yt:dQw4w9WgXcQ" or "bili:BV1xx411c7mD"
  provider: Provider
  rawId: string // YouTube videoId or BiliBili bvid
  title: string
  thumbnailUrl: string
  duration: number // seconds (0 if live)
  viewCount?: number
  danmakuCount?: number
  likeCount?: number
  publishedText?: string
  publishedAt?: number // epoch ms
  authorId: string
  authorName: string
  authorAvatar?: string
  isLive?: boolean
  cid?: number // BiliBili active cid
  aid?: number // BiliBili aid
}

export interface VideoPagePart {
  cid: number
  page: number
  title: string
  duration: number
}

export interface VideoChapter {
  title: string
  startTime: number // seconds
  endTime: number // seconds
  thumbnailUrl?: string
}

export interface SubtitleTrackInfo {
  id: string
  languageCode: string
  label: string
  url: string
  format: "vtt" | "srt" | "srv3" | "json3"
  isAutoGenerated?: boolean
}

export interface VideoQualityTrack {
  id: string
  label: string // e.g. "1080p60", "1080p", "720p", "4K"
  width: number
  height: number
  fps?: number
  bitrate?: number
  codec?: string
  delivery: "hls" | "sabr" | "dash" | "progressive"
  /** Direct URL or local proxy/file URL ready for VideoPlaybackController.open() */
  url: string
  /** Optional audio URL when paired outside MPD */
  audioUrl?: string
  /** Optional custom headers for VideoPlaybackController.open() */
  headers?: Record<string, string>
  /** Internal metadata for SABR or BiliBili DASH rebuilds */
  itag?: number
  qn?: number
}

export interface AudioStreamTrack {
  id: string
  label: string
  bitrate: number
  codec: string
  mimeType: string
  url: string
  itag?: number
  initRange?: string
  indexRange?: string
}

export interface StreamManifest {
  provider: Provider
  rawId: string
  delivery: "hls" | "sabr" | "dash" | "progressive"
  /** Primary playable source (HLS master m3u8, local SABR m3u8/mpd URL, or Bili DASH .mpd path/URL) */
  primaryUrl: string
  /** Preferred backend for VideoPlaybackController.open() */
  backend: "auto" | "native" | "system" | "remux"
  /** Custom HTTP headers required for playback (e.g. BiliBili Referer + User-Agent) */
  headers?: Record<string, string>
  qualities: VideoQualityTrack[]
  audioTracks: AudioStreamTrack[]
  subtitles: SubtitleTrackInfo[]
  danmakuXmlUrl?: string
  cid?: number
  isLive?: boolean
  duration: number
  /** Switch quality and return a resolved playable source + headers */
  resolveQuality?: (qualityId: string) => Promise<{
    url: string
    backend: "auto" | "native" | "system" | "remux"
    headers?: Record<string, string>
  }>
}

export interface VideoCollaborator {
  id: string
  name: string
  avatarUrl?: string
  subscriberCountText?: string
}

export interface VideoDetail extends UnifiedVideoItem {
  description: string
  subscriberCountText?: string
  /** 多頻道合作的影片；第一個是上傳者。 */
  collaborators?: VideoCollaborator[]
  pages?: VideoPagePart[] // BiliBili multi-page (分P)
  chapters?: VideoChapter[]
  relatedVideos: UnifiedVideoItem[]
  tags?: string[]
}

export interface CommentItem {
  id: string
  authorId: string
  authorName: string
  authorAvatar: string
  content: string
  likeCount: number
  publishedText: string
  replyCount?: number
  replies?: CommentItem[]
  /** 載入下一批回覆的游標；`null` 代表回覆已全數載完。 */
  replyCursor?: string | null
}

/** 留言排序：最熟 / 最新。 */
export type CommentSort = "top" | "newest"

export interface CommentQuery {
  sort?: CommentSort
  /** 下一批的游標；不給就是第一頁。 */
  cursor?: string | null
}

export interface CommentPage {
  comments: CommentItem[]
  /** 下一批的游標，null 代表沒有更多。 */
  cursor: string | null
}

export interface ChannelDetail {
  id: string // "yt:UC..." or "bili:12345"
  provider: Provider
  rawId: string
  name: string
  avatarUrl: string
  bannerUrl?: string
  description: string
  subscriberCountText?: string
  videos: UnifiedVideoItem[]
  nextPageToken?: string
}

export type SponsorCategory =
  | "sponsor"
  | "selfpromo"
  | "interaction"
  | "intro"
  | "outro"
  | "preview"
  | "music_offtopic"
  | "poi_highlight"

export interface SponsorSegment {
  uuid: string
  category: SponsorCategory
  actionType: "skip" | "mute" | "full" | "poi"
  startTime: number // seconds
  endTime: number // seconds
}

export interface SubscriptionChannel {
  id: string // "yt:UC..." or "bili:12345"
  provider: Provider
  rawId: string
  name: string
  avatarUrl: string
  subscribedAt: number
}

export interface WatchHistoryEntry {
  item: UnifiedVideoItem
  position: number // last playback position in seconds
  duration: number
  watchedAt: number
  cid?: number
  page?: number
}

export interface CustomPlaylist {
  id: string
  name: string
  description?: string
  createdAt: number
  updatedAt: number
  items: UnifiedVideoItem[]
}

export interface PlayerSettings {
  youtubeStreamMode: YoutubeStreamPreference
  preferredQualityHeight: number // e.g. 1080, 720, 2160
  defaultPlaybackRate: number
  sponsorBlockEnabled: boolean
  sponsorBlockAutoSkip: boolean
  sponsorBlockCategories: SponsorCategory[]
  danmakuEnabled: boolean
  danmakuOpacity: number // 0.1 .. 1.0
  danmakuSpeed: number // 0.5 .. 2.0
  danmakuArea: number // 0.25 | 0.5 | 0.75 | 1.0
  danmakuBlockedWords: string[]
  /** bili 播放中自動換 CDN 線路。 */
  biliLineSwitch: boolean
}

export interface ProviderAuthState {
  provider: Provider
  loggedIn: boolean
  username?: string
  userId?: string
  avatarUrl?: string
  cookieHeader: string
  cookies: Record<string, string>
  updatedAt: number
}

export type OfflineCacheMode = "hls" | "dash" | "http"

/** 離線下載項目：記錄足以重建 `VideoPlaybackCache` 查詢的來源資訊。 */
export interface OfflineDownload {
  id: string
  item: UnifiedVideoItem
  cid?: number
  page?: number
  qualityId: string
  qualityLabel: string
  delivery: StreamManifest["delivery"]
  cacheMode: OfflineCacheMode
  /** 下載時使用的來源網址（`prepare*` 與 `resolve*` 必須一致） */
  url: string
  headers?: Record<string, string>
  maximumBitRate?: number
  bytes: number
  duration: number
  downloadedAt: number
}

export interface DownloadTaskState {
  id: string
  title: string
  qualityLabel: string
  progress: number
  downloadedSegments: number
  totalSegments: number
  startedAt: number
  error: string | null
}
