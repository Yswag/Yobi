import { fetch } from "scripting"
import type { SubtitleTrackInfo } from "../../types"
import { BILI_REFERER, BILI_USER_AGENT, getBiliRequestHeaders, signWbiParams } from "./wbi"

const SUBTITLE_API: string = "https://api.bilibili.com/x/player/wbi/v2"

interface BiliSubtitleEntry {
  id?: number | string
  lan?: string
  lan_doc?: string
  subtitle_url?: string
  type?: number
  ai_type?: number
  ai_status?: number
}

function absoluteUrl(url: string): string {
  if (!url) return ""
  if (url.startsWith("//")) return `https:${url}`
  if (url.startsWith("http://")) return `https://${url.slice("http://".length)}`
  return url
}

export async function fetchBiliSubtitleTracks(
  bvid: string,
  cid: number,
): Promise<SubtitleTrackInfo[]> {
  try {
    const query: string = await signWbiParams({ bvid, cid })
    const response = await fetch(`${SUBTITLE_API}?${query}`, {
      headers: await getBiliRequestHeaders(),
      debugLabel: "Yobi bili subtitle list",
    })
    if (!response.ok) return []
    const json: any = await response.json()
    if (json?.code !== 0) return []
    const entries: unknown = json?.data?.subtitle?.subtitles
    if (!Array.isArray(entries)) return []

    const tracks: SubtitleTrackInfo[] = []
    for (const raw of entries as BiliSubtitleEntry[]) {
      const url: string = absoluteUrl(String(raw?.subtitle_url ?? ""))
      if (!url) continue
      const languageCode: string = String(raw?.lan ?? "")
      const generated: boolean = Number(raw?.ai_type ?? 0) !== 0 || Number(raw?.type ?? 0) === 1
      if (generated && raw?.ai_status !== undefined && Number(raw.ai_status) !== 2) continue
      tracks.push({
        id: String(raw?.id ?? languageCode),
        languageCode,
        label: String(raw?.lan_doc ?? languageCode) || languageCode,
        url,
        format: "bili",
        isAutoGenerated: generated,
        headers: { Referer: BILI_REFERER, "User-Agent": BILI_USER_AGENT },
      })
    }
    return tracks
  } catch {
    return []
  }
}
